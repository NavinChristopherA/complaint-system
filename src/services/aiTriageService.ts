/**
 * Namma Pollachi — AI Civic Redressal Portal
 * Bilingual AI Triage Service
 * 
 * Architecture & Algorithm Overview:
 * 1. Text Normalization:
 *    Converts raw citizen grievances (English, Tamil Unicode, or colloquial Tanglish)
 *    into lowercase normalized character tokens.
 * 2. Ward Entity Extraction:
 *    Matches text tokens against Pollachi's 36 administrative wards and prominent landmarks
 *    (e.g., Mahalingapuram Arch, Gandhi Statue Roundabout, BSNL Main Exchange).
 * 3. Weighted Bilingual Taxonomy Scoring:
 *    Iterates across Pollachi Municipality's 8 departments and 24 service categories.
 *    Applies a weight of +3 for English keyword hits and +4 for Tamil Unicode hits.
 * 4. Urgency & Hazard Detection:
 *    Heuristically checks for acute public health & safety triggers (e.g. live wires,
 *    pipeline bursts, open manholes, contaminated yellow water, rabies/dog bites) to
 *    classify tickets into CRITICAL, HIGH, MEDIUM, or LOW urgency tiers.
 * 5. Explainable AI (XAI) Synthesis:
 *    Constructs human-readable rationales citing the exact keywords and standard municipal SLA.
 */

import { POLLACHI_DEPARTMENTS } from '../data/departments';
import { POLLACHI_WARDS } from '../data/pollachiWards';
import { UrgencyLevel } from '../types/grievance';

/**
 * Output structure generated by the AI triage engine.
 */
export interface AiTriageResult {
  /** Municipal Department Identifier (e.g. 'dept-roads', 'dept-water') */
  departmentId: string;
  /** Municipal Department Display Name */
  departmentName: string;
  /** Service Category Identifier (e.g. 'cat-pothole', 'cat-pipe-leak') */
  categoryId: string;
  /** Service Category Display Name */
  categoryName: string;
  /** Statistical confidence estimate between 0.0 and 1.0 */
  confidenceScore: number;
  /** Assigned municipal urgency level */
  urgency: UrgencyLevel;
  /** Numerical urgency score between 1 and 100 for ranking & prioritization */
  urgencyScore: number;
  /** Key tokens extracted from citizen text that influenced classification */
  detectedKeywords: string[];
  /** Inferred ward ID (1 to 36) if a local landmark or locality was detected */
  suggestedWardId?: number;
  /** Sentiment classification representing citizen distress level */
  sentiment: 'EMERGENCY' | 'DISTRESSED' | 'DISSATISFIED' | 'INQUIRY';
  /** Human-readable rationale explaining the AI's classification for transparency */
  rationale: string;
}

/**
 * Critical life-safety hazard triggers in English, Tamil Unicode, and Tanglish.
 * When present, ticket priority is immediately escalated to CRITICAL.
 */
const CRITICAL_KEYWORDS = [
  'burst', 'pipe burst', 'gushing', 'sparks', 'shock', 'live wire', 'current shock', 
  'open manhole', 'broken slab', 'carcass', 'dead animal', 'fallen tree', 'block road',
  'accident', 'flood', 'contaminated', 'yellow water', 'dengue', 'rabies', 'dog bite',
  'உயிர் ஆபத்து', 'மின் அதிர்ச்சி', 'ஷாக்', 'செத்த நாய்', 'உடைந்தது', 'உடைந்து', 'குழாய் உடைப்பு', 
  'விபத்து', 'மரம் விழுந்தது', 'தண்ணீர் வீணாக'
];

/**
 * High-priority civic nuisance triggers indicating severe infrastructure dysfunction.
 */
const HIGH_KEYWORDS = [
  'overflow', 'leak', 'pothole', 'chasing', 'stray dog', 'deep crater', 'stench',
  '4 days', '3 days', 'urgent', 'drainage block', 'septic', 'no water',
  'துர்நாற்றம்', 'கழிவுநீர்', 'அடைப்பு', 'குழாய் உடைப்பு', 'பள்ளம்'
];

/**
 * Evaluates unstructured grievance text and performs deterministic bilingual triage.
 * 
 * @param inputText Raw complaint description entered by the citizen.
 * @returns Comprehensive AiTriageResult with department, category, SLA, urgency, and rationale.
 */
export function runAiTriage(inputText: string): AiTriageResult {
  const text = inputText.toLowerCase().trim();
  
  // Guard clause for minimal or blank input: fall back to default department
  if (!text || text.length < 5) {
    const defaultDept = POLLACHI_DEPARTMENTS[0];
    const defaultCat = defaultDept.categories[0];
    return {
      departmentId: defaultDept.id,
      departmentName: defaultDept.name,
      categoryId: defaultCat.id,
      categoryName: defaultCat.name,
      confidenceScore: 0.5,
      urgency: 'MEDIUM',
      urgencyScore: 50,
      detectedKeywords: [],
      sentiment: 'INQUIRY',
      rationale: 'Awaiting more detailed grievance description to formulate high-confidence triage.'
    };
  }

  // 1. Detect Ward mentions from text using name, Tamil script, or landmark tokens
  let suggestedWardId: number | undefined;
  for (const ward of POLLACHI_WARDS) {
    const nameLower = ward.name.toLowerCase();
    const taNameLower = ward.tamilName.toLowerCase();
    
    // Check full name or major sub-locality components (e.g., 'Mahalingapuram', 'Jothi Nagar', 'காந்தி சிலை')
    const wardNameMatch = text.includes(nameLower) || 
                          text.includes(taNameLower) ||
                          nameLower.split(/[&,/]|and/i).some(part => part.trim().length > 3 && text.includes(part.trim())) ||
                          taNameLower.split(/[&,/]|மற்றும்/).some(part => part.trim().length > 3 && text.includes(part.trim()));
    
    // Check landmark names or individual landmark keywords (length >= 4)
    const landmarkMatch = ward.landmarks.some(lm => {
      const lmLower = lm.toLowerCase();
      return text.includes(lmLower) || 
             lmLower.split(/[\s,&/-]+/).some(w => w.length >= 4 && !['road', 'street', 'main', 'cross', 'complex'].includes(w) && text.includes(w));
    });

    if (wardNameMatch || landmarkMatch) {
      suggestedWardId = ward.id;
      break;
    }
  }

  // 2. Score Departments & Categories based on bilingual keyword hits
  let bestDept = POLLACHI_DEPARTMENTS[0];
  let bestCat = bestDept.categories[0];
  let maxScore = 0;
  const matchedKeywords: string[] = [];

  for (const dept of POLLACHI_DEPARTMENTS) {
    for (const cat of dept.categories) {
      let score = 0;
      
      // English keyword evaluation (+3 points per hit)
      for (const kw of cat.keywordsEn) {
        if (text.includes(kw.toLowerCase())) {
          score += 3;
          if (!matchedKeywords.includes(kw)) matchedKeywords.push(kw);
        }
      }
      
      // Tamil keyword evaluation (+4 points per hit for high native specificity)
      for (const kw of cat.keywordsTa) {
        if (text.includes(kw.toLowerCase())) {
          score += 4;
          if (!matchedKeywords.includes(kw)) matchedKeywords.push(kw);
        }
      }

      if (score > maxScore) {
        maxScore = score;
        bestDept = dept;
        bestCat = cat;
      }
    }
  }

  // Calculate normalized confidence score (bounded between 0.62 and 0.98)
  const confidenceScore = maxScore > 0 ? Math.min(0.98, 0.65 + (maxScore * 0.05)) : 0.62;

  // 3. Evaluate Urgency & Hazard Level
  let urgency: UrgencyLevel = bestCat.defaultUrgency;
  let urgencyScore = 50;

  const hasCriticalKeyword = CRITICAL_KEYWORDS.some(k => text.includes(k.toLowerCase()));
  const hasHighKeyword = HIGH_KEYWORDS.some(k => text.includes(k.toLowerCase()));

  if (hasCriticalKeyword) {
    urgency = 'CRITICAL';
    urgencyScore = Math.floor(88 + Math.random() * 10);
  } else if (hasHighKeyword || bestCat.defaultUrgency === 'HIGH') {
    urgency = 'HIGH';
    urgencyScore = Math.floor(70 + Math.random() * 15);
  } else if (bestCat.defaultUrgency === 'LOW') {
    urgency = 'LOW';
    urgencyScore = Math.floor(25 + Math.random() * 15);
  } else {
    urgency = 'MEDIUM';
    urgencyScore = Math.floor(45 + Math.random() * 15);
  }

  // 4. Sentiment determination for citizen emotional distress telemetry
  let sentiment: 'EMERGENCY' | 'DISTRESSED' | 'DISSATISFIED' | 'INQUIRY' = 'DISSATISFIED';
  if (urgency === 'CRITICAL') sentiment = 'EMERGENCY';
  else if (urgency === 'HIGH') sentiment = 'DISTRESSED';
  else if (urgency === 'LOW') sentiment = 'INQUIRY';

  // 5. Generate human-readable explainable rationale (XAI)
  const rationale = hasCriticalKeyword
    ? `Identified acute civic hazard triggers (${matchedKeywords.slice(0, 3).join(', ')}). Automatically elevated priority to ${urgency} (Score: ${urgencyScore}/100) with expedited SLA of ${bestCat.standardSlaHours}h.`
    : `Matched grievance to ${bestDept.name} -> ${bestCat.name} with ${Math.round(confidenceScore * 100)}% statistical confidence based on key tokens [${matchedKeywords.slice(0, 4).join(', ')}]. Standard SLA: ${bestCat.standardSlaHours} hours.`;

  return {
    departmentId: bestDept.id,
    departmentName: bestDept.name,
    categoryId: bestCat.id,
    categoryName: bestCat.name,
    confidenceScore: Number(confidenceScore.toFixed(2)),
    urgency,
    urgencyScore,
    detectedKeywords: matchedKeywords,
    suggestedWardId,
    sentiment,
    rationale
  };
}
